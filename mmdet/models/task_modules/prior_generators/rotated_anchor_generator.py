from typing import Tuple

import torch
from torch import Tensor

from mmdet.registry import TASK_UTILS
from mmdet.structures.bbox import RotatedBoxes
from .anchor_generator import AnchorGenerator


@TASK_UTILS.register_module()
class RotatedAnchorGenerator(AnchorGenerator):
    """Anchor generator returning rotated boxes.

    The base anchors are generated by :class:`AnchorGenerator`, converted to
    ``(cx, cy, w, h, angle)`` format, and returned as :class:`RotatedBoxes`.

    Args:
        angle_version (str, optional): If provided, anchors are regularized
            with this convention. Base anchors use angle zero.
        **kwargs: Arguments forwarded to :class:`AnchorGenerator`.
    """

    def __init__(self, angle_version: str = None, **kwargs) -> None:
        if angle_version not in (None, 'oc', 'le90', 'le135', 'r360'):
            raise ValueError(
                "angle_version must be None, 'oc', 'le90', 'le135' or "
                f"'r360', but got {angle_version!r}.")
        self.angle_version = angle_version
        super().__init__(**kwargs)

    def single_level_grid_priors(self,
                                 featmap_size: Tuple[int],
                                 level_idx: int,
                                 dtype: torch.dtype = torch.float32,
                                 device: str = 'cuda') -> Tensor:
        anchors = super().single_level_grid_priors(
            featmap_size, level_idx, dtype=dtype, device=device)
        center_x = (anchors[..., 0] + anchors[..., 2]) / 2
        center_y = (anchors[..., 1] + anchors[..., 3]) / 2
        width = anchors[..., 2] - anchors[..., 0]
        height = anchors[..., 3] - anchors[..., 1]
        rotated = torch.stack([
            center_x, center_y, width, height,
            anchors.new_zeros(width.shape)
        ],
                              dim=-1)
        rotated_boxes = RotatedBoxes(rotated, clone=False)
        if self.angle_version is not None:
            rotated_boxes.regularize_boxes(self.angle_version)
        return rotated_boxes


__all__ = ['RotatedAnchorGenerator']
